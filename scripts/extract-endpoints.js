#!/usr/bin/env node

/**
 * Neurothumb - Modal Endpoint Extraction Utility
 * 
 * This script extracts Modal endpoints from deployment logs
 * and generates a .env.local file with the extracted values.
 * 
 * Usage:
 *   node scripts/extract-endpoints.js [--output .env.local]
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// ============================================================================
// Configuration
// ============================================================================

const OUTPUT_FILE = process.argv.includes('--output') 
  ? process.argv[process.argv.indexOf('--output') + 1]
  : '.env.local';

const ENDPOINT_PATTERN = /https:\/\/[a-zA-Z0-9-]+--crossaint-[a-zA-Z0-9-]+\.modal\.run/g;

// ============================================================================
// Helper Functions
// ============================================================================

function log(message, type = 'info') {
  const colors = {
    info: '\x1b[36m',    // Cyan
    success: '\x1b[32m', // Green
    warning: '\x1b[33m', // Yellow
    error: '\x1b[31m',   // Red
    reset: '\x1b[0m'
  };

  const prefix = {
    info: 'ℹ',
    success: '✓',
    warning: '⚠',
    error: '✗'
  };

  console.log(`${colors[type]}${prefix[type]}${colors.reset} ${message}`);
}

function extractEndpointsFromModalOutput(output) {
  const endpoints = {
    analyze: null,
    analyzeChannel: null
  };

  const matches = output.match(ENDPOINT_PATTERN) || [];

  for (const match of matches) {
    if (match.includes('-analyze-channel')) {
      endpoints.analyzeChannel = match;
    } else if (match.includes('-analyze')) {
      endpoints.analyze = match;
    }
  }

  return endpoints;
}

function getModalDeploymentInfo() {
  try {
    log('Fetching Modal deployment information...');
    
    // Try to get deployment info from Modal CLI
    const output = execSync('modal app list --json 2>/dev/null || modal app list', {
      encoding: 'utf-8',
      stdio: ['pipe', 'pipe', 'pipe']
    });

    return output;
  } catch (error) {
    log('Could not fetch deployment info from Modal CLI', 'warning');
    return null;
  }
}

function readDeploymentLogs() {
  try {
    log('Reading Modal deployment logs...');
    
    // Try to read from common log locations
    const logPaths = [
      path.join(process.env.HOME || process.env.USERPROFILE, '.modal', 'logs'),
      path.join(process.cwd(), '.modal-logs'),
      path.join(process.cwd(), 'modal_backend', '.logs')
    ];

    for (const logPath of logPaths) {
      if (fs.existsSync(logPath)) {
        const files = fs.readdirSync(logPath);
        const latestLog = files
          .map(f => ({
            name: f,
            time: fs.statSync(path.join(logPath, f)).mtime.getTime()
          }))
          .sort((a, b) => b.time - a.time)[0];

        if (latestLog) {
          const content = fs.readFileSync(path.join(logPath, latestLog.name), 'utf-8');
          return content;
        }
      }
    }
  } catch (error) {
    log(`Error reading logs: ${error.message}`, 'warning');
  }

  return null;
}

function generateEnvContent(endpoints) {
  const timestamp = new Date().toISOString();
  
  return `# ============================================================================
# NEUROTHUMB - BYOK Configuration
# Generated by extract-endpoints.js on ${timestamp}
# ============================================================================

# Modal Configuration
MODAL_ENDPOINT_URL=${endpoints.analyze || 'https://your-username--crossaint-analyze.modal.run'}
MODAL_CHANNEL_ENDPOINT_URL=${endpoints.analyzeChannel || 'https://your-username--crossaint-analyze-channel.modal.run'}

# Supabase Configuration (REQUIRED - Add your credentials)
NEXT_PUBLIC_SUPABASE_URL=
NEXT_PUBLIC_SUPABASE_ANON_KEY=
SUPABASE_SERVICE_ROLE_KEY=

# Gemini Configuration (OPTIONAL)
GEMINI_API_KEY=

# Modal Credentials (OPTIONAL - for programmatic deployment)
MODAL_TOKEN_ID=
MODAL_TOKEN_SECRET=
`;
}

function saveEnvFile(content, filename) {
  try {
    // Backup existing file if it exists
    if (fs.existsSync(filename)) {
      const backupName = `${filename}.bak.${Date.now()}`;
      fs.copyFileSync(filename, backupName);
      log(`Backed up existing ${filename} to ${backupName}`, 'warning');
    }

    fs.writeFileSync(filename, content, 'utf-8');
    log(`Saved configuration to ${filename}`, 'success');
    return true;
  } catch (error) {
    log(`Failed to save ${filename}: ${error.message}`, 'error');
    return false;
  }
}

function displayEndpoints(endpoints) {
  console.log('\n' + '='.repeat(60));
  console.log('Modal Endpoints Extracted');
  console.log('='.repeat(60));
  
  if (endpoints.analyze) {
    console.log(`\nSingle Thumbnail Analysis:`);
    console.log(`  ${endpoints.analyze}`);
  } else {
    console.log(`\nSingle Thumbnail Analysis: NOT FOUND`);
  }

  if (endpoints.analyzeChannel) {
    console.log(`\nChannel Analysis:`);
    console.log(`  ${endpoints.analyzeChannel}`);
  } else {
    console.log(`\nChannel Analysis: NOT FOUND (will be auto-derived)`);
  }

  console.log('\n' + '='.repeat(60) + '\n');
}

function promptForManualEntry() {
  const readline = require('readline');
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });

  return new Promise((resolve) => {
    console.log('\nCould not automatically extract endpoints.');
    console.log('You can manually enter them now, or add them to .env.local later.\n');

    rl.question('Enter Modal endpoint URL (or press Enter to skip): ', (analyze) => {
      rl.question('Enter Modal channel endpoint URL (or press Enter to skip): ', (channel) => {
        rl.close();
        resolve({
          analyze: analyze || null,
          analyzeChannel: channel || null
        });
      });
    });
  });
}

// ============================================================================
// Main Function
// ============================================================================

async function main() {
  log('Neurothumb - Modal Endpoint Extraction Utility', 'info');
  console.log('');

  let endpoints = {
    analyze: null,
    analyzeChannel: null
  };

  // Try to get endpoints from Modal deployment info
  const deploymentInfo = getModalDeploymentInfo();
  if (deploymentInfo) {
    endpoints = extractEndpointsFromModalOutput(deploymentInfo);
  }

  // Try to get endpoints from logs
  if (!endpoints.analyze && !endpoints.analyzeChannel) {
    const logs = readDeploymentLogs();
    if (logs) {
      endpoints = extractEndpointsFromModalOutput(logs);
    }
  }

  // Display found endpoints
  displayEndpoints(endpoints);

  // If no endpoints found, ask for manual entry
  if (!endpoints.analyze && !endpoints.analyzeChannel) {
    const manual = await promptForManualEntry();
    endpoints = { ...endpoints, ...manual };
  }

  // Generate and save .env file
  const envContent = generateEnvContent(endpoints);
  
  if (saveEnvFile(envContent, OUTPUT_FILE)) {
    log('Configuration file created successfully', 'success');
    log(`Next step: Fill in Supabase credentials in ${OUTPUT_FILE}`, 'info');
    log('See ENV_SETUP.md for detailed instructions', 'info');
  } else {
    log('Failed to create configuration file', 'error');
    process.exit(1);
  }
}

// Run main function
main().catch(error => {
  log(`Error: ${error.message}`, 'error');
  process.exit(1);
});
